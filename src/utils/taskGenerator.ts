export function generateSingleTask(
  taskNum: 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8 | 9
): TaskItem {
  const ticket = generateExamTicket('steps');
  const task = ticket.tasks[taskNum - 1];
  if (taskNum === 5) {
    const task4 = ticket.tasks[3];
    const dfStep = task4.steps[0]?.ans[0] || '';
    const critStep = task4.steps[1]?.ans[0] || '';
    const isRejected = task.steps[0]?.ans.includes('невозможно');
    if (isRejected) {
      const empMatch = task4.text.match(/\\chi\^2_\{\\text\{эмп\}\}\s*=\s*([0-9,]+)/);
      const empVal = empMatch ? empMatch[1] : '';
      return {
        ...task,
        text: `${task.text} (По данным задания №4: $df = ${dfStep}$, $\\chi^2_{\\text{эмп}} = ${empVal}$, табличный порог $\\chi^2_{\\text{табл}} = ${critStep}$.)`,
      };
    }
  }
  return task;
}
